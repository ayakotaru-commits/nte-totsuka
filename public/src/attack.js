const sstep = (t) => { t = Math.max(0, Math.min(1, t)); return t * t * (3 - 2 * t); };

// 表を時間 t で引く (キー同士をなめらかにつなぐ)
export function samplePose(step, ph, t) {
  const keys = TABLE[`${step}:${ph}`];
  if (t <= keys[0][0]) return keys[0].slice(1);
  for (let i = 1; i < keys.length; i++) {
    if (t <= keys[i][0]) {
      const a = keys[i - 1], b = keys[i], u = sstep((t - a[0]) / (b[0] - a[0]));
      return a.slice(1).map((v, j) => v + (b[j + 1] - v) * u);
    }
  }
  return keys[keys.length - 1].slice(1);
}

// 軌跡を出している時間か
export function trailOn(step, ph, t) {
  const r = TRAIL[`${step}:${ph}`];
  return !!r && t >= r[0] && t <= r[1];
}
