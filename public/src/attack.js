const sm = (u) => { u = Math.max(0, Math.min(1, u)); return u * u * (3 - 2 * u); };
// 手順・局面・時間から、体ごと回す角度 (rad、+ = 左回り) を返す。回り終えたら 0 (1 周は 0 と同じ向き)
export function spinAt(step, ph, t) {
  if (step === 3 && ph === 0) { const u = (t - SPIN3.from) / (SPIN3.to - SPIN3.from); return u <= 0 || u >= 1 ? 0 : Math.PI * 2 * sm(u); }
  if (step === 4 && ph === 1) { const u = t / SPIN.dur; return u >= 1 ? 0 : Math.PI * 2 * SPIN.turns * (1 - (1 - u) * (1 - u)); }
  return 0;
}

